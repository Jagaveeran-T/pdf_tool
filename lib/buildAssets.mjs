// Runs before dev and build (npm run assets). No network access.
//  1. copies the pdf.js worker into public/ so it is self-hosted
//  2. writes public/ads.txt from NEXT_PUBLIC_ADSENSE_ID (or a clearly marked pending state)
//  3. writes public/_redirects (www -> apex) from NEXT_PUBLIC_SITE_URL
//  4. generates icons and Open Graph images from inline SVG with sharp
//  5. fails the build when STRICT_SITE_CONFIG=true and required site values are missing
import { copyFileSync, existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { createRequire } from "node:module";

const require = createRequire(import.meta.url);
const root = process.cwd();
const pub = (...p) => join(root, "public", ...p);
// Read .env.local too (npm runs this script before Next.js loads it). Real environment variables win.
try {
  const file = join(root, ".env.local");
  if (existsSync(file)) {
    for (const line of readFileSync(file, "utf8").split(/\r?\n/)) {
      const m = /^\s*([A-Z0-9_]+)\s*=\s*([^#]*?)\s*(?:#.*)?$/.exec(line);
      if (m && process.env[m[1]] === undefined) process.env[m[1]] = m[2];
    }
  }
} catch (e) {
  console.warn("[assets] could not read .env.local:", e.message);
}
const env = (k) => (process.env[k] ?? "").trim();

// --- 5. strict config -------------------------------------------------------
const strict = env("STRICT_SITE_CONFIG") === "true";
const missing = ["NEXT_PUBLIC_SITE_URL", "NEXT_PUBLIC_SITE_NAME", "NEXT_PUBLIC_CONTACT_EMAIL"].filter((k) => !env(k));
if (missing.length) {
  const msg = `Missing site settings: ${missing.join(", ")}. Defaults (example.com) must not go live.`;
  if (strict) {
    console.error(`\n[assets] ERROR: ${msg}\n`);
    process.exit(1);
  }
  console.warn(`[assets] WARNING: ${msg}`);
}

// --- 1. pdf.js worker -------------------------------------------------------
try {
  const pkgDir = dirname(require.resolve("pdfjs-dist/package.json"));
  const src = join(pkgDir, "build", "pdf.worker.min.mjs");
  if (existsSync(src)) copyFileSync(src, pub("pdf.worker.min.mjs"));
  else console.warn("[assets] pdf.worker.min.mjs not found in pdfjs-dist/build");
} catch (e) {
  console.warn("[assets] could not copy pdf.js worker:", e.message);
}

// --- 2. ads.txt -------------------------------------------------------------
const clientId = env("NEXT_PUBLIC_ADSENSE_ID");
const pubId = clientId.replace(/^ca-/, "");
if (/^pub-\d{10,20}$/.test(pubId)) {
  writeFileSync(pub("ads.txt"), `google.com, ${pubId}, DIRECT, f08c47fec0942fa0\n`);
  console.log(`[assets] ads.txt written for ${pubId}`);
} else {
  // Always rewrite, so a publisher ID from an earlier build can never linger in ads.txt.
  writeFileSync(
    pub("ads.txt"),
    "# PENDING: no AdSense publisher ID configured yet.\n# Set NEXT_PUBLIC_ADSENSE_ID and rebuild. The line will be:\n# google.com, pub-XXXXXXXXXXXXXXXX, DIRECT, f08c47fec0942fa0\n",
  );
}

// --- 3. _redirects ----------------------------------------------------------
try {
  const site = env("NEXT_PUBLIC_SITE_URL");
  const lines = ["# Generated by lib/buildAssets.mjs. Cloudflare Pages already redirects /path to /path/ for exported pages."];
  if (site) {
    const host = new URL(site).host.replace(/^www\./, "");
    lines.push(`https://www.${host}/* https://${host}/:splat 301`);
  } else {
    lines.push("# NEXT_PUBLIC_SITE_URL not set: no www redirect generated.");
  }
  writeFileSync(pub("_redirects"), lines.join("\n") + "\n");
} catch (e) {
  console.warn("[assets] could not write _redirects:", e.message);
}

// --- 4. icons and OG images -------------------------------------------------
try {
  const sharp = (await import("sharp")).default;
  const name = env("NEXT_PUBLIC_SITE_NAME") || "Pagewise";
  const esc = (s) => s.replace(/&/g, "&amp;").replace(/</g, "&lt;");
  mkdirSync(pub("icons"), { recursive: true });
  mkdirSync(pub("og"), { recursive: true });

  const iconSvg = (size) =>
    Buffer.from(`<svg xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}" viewBox="0 0 64 64">
<rect width="64" height="64" rx="14" fill="#2563eb"/>
<path d="M20 12h17l9 9v31a2 2 0 0 1-2 2H20a2 2 0 0 1-2-2V14a2 2 0 0 1 2-2z" fill="#fff"/>
<path d="M37 12v9h9z" fill="#bfdbfe"/>
<rect x="24" y="30" width="16" height="3" rx="1.5" fill="#2563eb"/><rect x="24" y="37" width="16" height="3" rx="1.5" fill="#93c5fd"/><rect x="24" y="44" width="10" height="3" rx="1.5" fill="#93c5fd"/></svg>`);
  writeFileSync(pub("icons", "favicon.svg"), iconSvg(64));
  await sharp(iconSvg(192)).png().toFile(pub("icon-192.png"));
  await sharp(iconSvg(512)).png().toFile(pub("icon-512.png"));
  await sharp(iconSvg(180)).png().toFile(pub("apple-touch-icon.png"));

  const pages = {
    default: ["Free PDF tools", "Convert, merge, split and compress PDFs in your browser"],
    "image-to-pdf": ["Image to PDF", "JPG, PNG and WebP into one PDF"],
    "jpg-to-pdf": ["JPG to PDF", "Photos and scans into a PDF"],
    "merge-pdf": ["Merge PDF", "Join PDF files in the order you choose"],
    "split-pdf": ["Split PDF", "Extract pages or cut by range"],
    "compress-pdf": ["Compress PDF", "Make a PDF smaller, in your browser"],
  };
  for (const [file, [title, sub]] of Object.entries(pages)) {
    const svg = Buffer.from(`<svg xmlns="http://www.w3.org/2000/svg" width="1200" height="630" viewBox="0 0 1200 630">
<rect width="1200" height="630" fill="#eff6ff"/><rect x="0" y="0" width="16" height="630" fill="#2563eb"/>
<rect x="80" y="90" width="96" height="96" rx="22" fill="#2563eb"/>
<path d="M112 110h34l18 18v50a4 4 0 0 1-4 4h-48a4 4 0 0 1-4-4v-64a4 4 0 0 1 4-4z" fill="#fff"/>
<text x="80" y="330" font-family="Arial, Helvetica, sans-serif" font-size="84" font-weight="700" fill="#0f172a">${esc(title)}</text>
<text x="80" y="410" font-family="Arial, Helvetica, sans-serif" font-size="40" fill="#475569">${esc(sub)}</text>
<text x="80" y="560" font-family="Arial, Helvetica, sans-serif" font-size="34" font-weight="600" fill="#2563eb">${esc(name)}  ·  Files stay on your device</text></svg>`);
    await sharp(svg).png().toFile(pub("og", `${file}.png`));
  }
} catch (e) {
  console.warn("[assets] icon/OG generation skipped:", e.message);
}
